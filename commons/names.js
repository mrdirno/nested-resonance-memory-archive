/* THE COMMONS — the name table. Data only; commons/names.html is the surface,
 * commons/commons.js is the engine all three surfaces share.
 *
 * WHAT THIS IS. One OBJECT, every name the field says for it, and the one name to
 * write on the order. A man gets handed a word by somebody from another trade,
 * another region or another counter, and either he knows it or the wrong thing
 * shows up on the truck. Nobody owns this document, which is why it does not
 * exist anywhere else.
 *
 * WHAT THIS IS NOT — AND THIS IS THE WHOLE SAFETY DESIGN. It is not a spec, not a
 * catalog, and not authority about the OBJECT. It is evidence about the WORD, and
 * it will be read as authority about the object anyway, so the guard lives in the
 * data shape rather than in the copy:
 *
 *   n   THE ORDER NAME. The plain generic, and the only string on the row that a
 *       man should write down. Never a trademark.
 *   o   THE OBJECT, declared in one clause a reviewer can hold against the alias
 *       list and say yes or no to. A row without it is a word with no referent.
 *   a   what the field says, each with WHO SAYS IT and a KIND — and the kind, not
 *       the writer, decides the framing on the page:
 *         tm  → "a brand people say"   (never what to write on the order)
 *         reg → "you might hear"       (never "it is called")
 *         say → "the field says"
 *         sup → "the counter says"
 *   no  the near-miss guard. The rows that earn this page are the ones where the
 *       wrong word gets the wrong OBJECT walked over to you, which is a different
 *       failure from not knowing the word at all.
 *
 * NO NUMBERS, ANYWHERE. Not in a name, not in an object clause, not in a guard.
 * A row may not separate near-names by size, depth, gang, gauge or rating —
 * a name that needs a number to be right is certified data we do not ship, and
 * the gate fails the build on a single digit.
 *
 * IT IS ALSO AN INDEX, and that is the reason it is not a glossary. Every alias
 * here is searchable from the OTHER commons surfaces through shared/find.js:
 * type "stinger" into the gear list and the extension cord comes up, though that
 * word appears nowhere in gear.js. commons.js §THE ALIAS INDEX has the join, the
 * deploy counts it, and tools/toolkit-gates/commons-names.mjs derives a routing
 * probe from every alias that is not already on the gear page.
 *
 * PROVENANCE. Seeded 2026-08-14 by a fan-out — one vocabulary pass per trade pair
 * plus a universal pass, ninety-eight candidates — then cut by three independent
 * adversarial lenses: a rails reviewer holding the list above, a journeyman
 * rejecting slang from a video rather than a jobsite, and a partition reviewer
 * owning the tags and killing rows nobody would ever type. The seed is the floor,
 * not the ceiling: every shop and region has its own word, and a correction from
 * someone who does the work outranks anything here.
 *
 * Author: Aldrin Payopay <aldrin.gdf@gmail.com>
 */

