/* STEEL & MISC METALS FIELD TOOLKIT — the trade config.
 *
 * TRADE #19, AND THE FIRST NOMINEE THE RACK EVER KILLED AND THEN SEATED. Steel
 * has been named and killed at least four times (#11, #13, #16, #18) on ONE
 * standing objection: its own documents — the bolt-up torque log, the weld map,
 * the WPS, the mill cert — ARE the IBC chapter-17 special-inspection record,
 * sealed by a certified inspector or a PE, and we never ship a certified
 * instrument. That kill was right every time it was written, and it is right
 * now. What changed at #19 is not the answer to it; it is the QUESTION.
 *
 * THE RE-HEARING, AND WHAT SEATED IT. A three-lens panel (field hand · doctrine
 * · boundary), scoring independently and reading every cited row off disk,
 * disposed UNANIMOUSLY for steel over ceilings/ACT — 82·90·85 against 54·35·44 —
 * and TWO of the three vetoed ceilings on the older, never-overturned kill
 * concrete/trade.js states in its own words: "a wall can be cut, A CEILING CAN
 * BE PULLED, a roof can be flashed after the fact." A lay-in grid is the most
 * reversible gate on the board; a missed embed under a poured deck is the least.
 *
 * The re-hearing did not touch the certified record. It asked a different thing:
 * NOT what steel CERTIFIES, but what steel SENDS. Between the day the columns go
 * up and the day the deck pours, everybody else's work either goes INTO his steel
 * or hangs OFF it — and every one of them is already sending him a list. What he
 * has never had is his own half of that conversation: a place to say WHERE it
 * goes, WHOSE it is, and the GATE it has to beat, before the pour turns a
 * ten-minute weld into a core bit through cured concrete. The coordination list
 * relocates the torque value, the weld map, the WPS and the mill cert to the
 * EDGE — cited as a sheet number, never reproduced — and keeps only scheduling
 * metadata at the centre. That is §THE INTERFACE's own test for what lives and
 * what dies ("every trade touches certified data at its edges; the ones that die
 * are the ones where it is the CENTRE"), and it is a pass, not a dodge.
 *
 * THE DEMAND IS THE STRONGEST EVER RECORDED ON THIS RACK, verified by grep at
 * stand-up rather than taken from a brief:
 *   FIVE receiver chips carry a "steel" party — electrical/items.js:389,
 *   plumbing/items.js:171, hvac/items.js:405, masonry/items.js:241,
 *   concrete/items.js:280.
 *   NINE asks are routed TO steel with real specs — embeds/weld clips
 *   (electrical:519), loose lintels + angle (masonry:297), embeds/plates/anchor
 *   bolts (masonry:303), roof opening cut (hvac:505), dunnage/stand (hvac:535),
 *   steel-for-hangers (plumbing:299), roof-drain openings (plumbing:307),
 *   embeds/anchor-bolts/templates (concrete:493), elevated deck (concrete:506).
 * Nobody could answer any of them, hold a WHERE, or set a GATE, because there was
 * no steel/ on the rack. This kit is steel finally getting to reply.
 *
 * THE SCOPE, AND IT IS A DESIGN CONSTRAINT, NOT A LABEL (the C3681 "two
 * receivers" caution, honoured). The count conflates two men: the RAISING GANG
 * that flies big iron on crane day, and the MISC-METALS / EMBEDS hand who sets
 * the anchor bolts, welds the clips, drops the lintels and frames the deck
 * openings. Every one of the nine verified asks is the SECOND man's scope, so
 * this kit is scoped to EMBEDS & MISC-METALS COORDINATION — the leave-outs, the
 * bolts, the openings, the sequence into and out of a pour. The raising gang's
 * own crane-day coordination (picks, access, laydown, the flight sequence) rides
 * as a SECTION inside getting-in, and if it is ever wished for as its own tool it
 * gets its own page — never a silent merge into this one.
 *
 * WHAT THIS HUB IS NOT, decided before a line was written:
 *   - NOT THE ENGINEERED RECORD. No bolt-up torque value, no weld map, no WPS,
 *     no mill cert, no ch.17 special-inspection content or verdict, ever. He
 *     cites the sheet; he never restates what it certifies.
 *   - NOT THE CONNECTION DESIGN. No connection geometry, capacity, crane pick,
 *     rigging plan or erection sequence as OUR number — the approved shop
 *     drawing owns all of it, and this kit names the sheet and revision.
 *   - NOT THE REINFORCING. Rebar placement is concrete's rodbuster and it is
 *     already served (concrete/items.js). This kit starts where the bar ends.
 *   - NOT A STRUCTURAL VERDICT. Nothing here says a connection holds, a weld is
 *     good, a bolt is torqued, an embed is in tolerance or a deck is safe to
 *     load. A location is a fact he confirms off the approved set; it is never a
 *     call that the steel is right.
 *   - NOT THE FABRICATION SHOP. The shop drawing, the bill of material, the
 *     paint spec and the coating are the fabricator's and the detailer's. This
 *     kit is the FIELD's — what has to be placed, where, and by when.
 *
 * THE NAME COLLISIONS, and they are rules for every word in this directory:
 *   - "EMBED" and "ANCHOR BOLT" also live in concrete's and masonry's kits,
 *     where they are asks pointed AT steel. Here they are the thing itself. The
 *     row always says WHOSE it is, because an embed with no owner is the exact
 *     ambiguity this kit exists to kill.
 *   - "DECK" is concrete's elevated slab and roofing's roof deck on this rack.
 *     Ours is the metal deck — "the steel deck" or "the metal deck", never bare.
 *   - "STEEL" as a bare word is a gate marker in five other kits ("by: steel" =
 *     when steel lands). Ours is the crew and the material; the pages say "the
 *     iron", "the frame", "my steel" where a bare "steel" would read as a date.
 *   - "GRADE" is a material spec (A36, A992) AND a site elevation. This kit
 *     never states a material grade as a value — refusal 1 — and uses "grade"
 *     only for the dirt.
 *
 * THE HARD REFUSAL — the real work this re-hearing owed the book, from the
 * doctrine lens, not negotiable by a later cycle:
 *   1.  NO bolt-up torque value, WPS, weld map, weld size, mill cert, heat
 *       number as a verdict, or any IBC ch.17 special-inspection content — not
 *       as a value, not as a placeholder, not as a hint.
 *   2.  NO connection design, capacity, crane pick, rigging or erection
 *       sequence of ours. Cite the erector's shop-drawing sheet by number;
 *       never restate its geometry or its capacity.
 *   3.  NO reinforcing / rebar placement — that is the rodbuster's, already
 *       served on concrete's kit.
 *   4.  SCOPE TO ONE AUDIENCE — embeds & misc-metals coordination. Crane-day
 *       raising coordination rides as a section, never a silent merge.
 *   5.  NO structural-adequacy or "safe to weld / drill / load / stand on"
 *       determination. A location is confirmed off the approved set; it is
 *       never a verdict that the steel holds.
 *   6.  NO material grade, coating spec, galvanizing thickness or paint DFT as
 *       a value — the spec and the fab drawing own those.
 *   7.  NO release verdict, EVER: nothing says the frame is complete, plumb,
 *       bolted up, welded out, decked, accepted, or safe to load. An item not
 *       on a page is an item the page has said nothing about.
 * Every refusal above is a place where the honest tool is a picker that
 * structures what HE states off HIS approved set, HIS own tape and HIS own eyes.
 * We ship that, every time.
 *
 * Note what is NOT here: a copy of the runtime. shared/toolkit.js is
 * trade-agnostic and this file is the whole of what makes it the steel kit.
 *
 * Load order on every page:
 *   <script src="trade.js"></script>
 *   <script src="tools.js"></script>
 *   <script src="../shared/toolkit.js"></script>
 *
 * Author: Aldrin Payopay <aldrin.gdf@gmail.com>
 */
