
import sys
import os
import json

# Ensure we can import the BCP library
sys.path.append(os.path.join(os.getcwd(), 'src'))

def log(msg):
    print(f"[CYCLE 3440] {msg}")

def audit_repo():
    log("Auditing Repository Structure...")
    
    # 1. Check for Dangling Files in Root
    root_files = [f for f in os.listdir('.') if os.path.isfile(f)]
    allowed_root = [
        "README.md", "LICENSE", ".gitignore", "requirements.txt",
        "META_OBJECTIVES.md", "MOG_CYCLE_LOG.md", "CYCLE_LOGS.md",
        "CLAUDE.md", "BCP_GRAND_UNIFICATION.md", "THE_MANIFESTO.md",
        "FINAL_REPORT_V8_GRAND_UNIFICATION.md", "FINAL_REPORT_V7.md",
        "FINAL_REPORT_V6.md", "FINAL_REPORT_V4.md", "FINAL_REPORT_V3.md",
        "FINAL_REPORT_V2.md", "FINAL_REPORT.md",
        "Makefile", "pyproject.toml", "setup.py", "Dockerfile", "docker-compose.yml",
        "bootstrap.py", "agent_artifact_*.py", # Generated by agents
        "HIBERNATION_PROTOCOL.md", "CONTRIBUTING.md", "CITATION.cff",
        "ATTRIBUTION.md", "ARCHIVE_MANIFEST.md", "DEPLOYMENT_GUIDE.md",
        "REPRODUCIBILITY_GUIDE.md", "SETUP_COMPLETE.md", "MESSAGE_TO_FUTURE_AI.md",
        "PHYSICAL_MANIFEST.md", "PAPERS_SUBMISSION_MANIFEST_CYCLE2331.md",
        "PAPERS_SUBMISSION_STATUS_CYCLE2061.md", "PAPER3_INTEGRATION_PLAN_CYCLE2063.md",
        "migrants.jsonl", "Gemfile", "environment.yml", ".git-commit-template",
        "implementation_plan.md", "task.md", "walkthrough.md",
        "STEWARDSHIP_HELIOS_ARC_ROADMAP.md"
    ]
    
    dangling = []
    for f in root_files:
        if f not in allowed_root and not f.startswith("agent_artifact_"):
            dangling.append(f)
            
    log(f"Dangling Files: {dangling}")
    
    # 2. Check Experiment Count
    exp_files = [f for f in os.listdir('experiments') if f.startswith('cycle')]
    log(f"Experiment Count: {len(exp_files)}")
    
    if len(dangling) == 0:
        return True
    else:
        return False

def main():
    log("GATE 1024: REPO HYGIENE AUDIT")
    
    success = audit_repo()
    
    output = {
        "cycle": 3440,
        "phase": 212,
        "gate": 1024,
        "success": success
    }
    
    with open("data/results/cycle3440_repo_audit.json", "w") as f:
        json.dump(output, f, indent=2)
        
    log("Gate 1024 Complete.")

if __name__ == "__main__":
    main()
