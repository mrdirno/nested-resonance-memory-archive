/* DOORS & HARDWARE FIELD TOOLKIT — the trade config.
 *
 * TRADE #15, AND THE FIRST ONE THAT HAD ALREADY LOST TWICE. Doors took one
 * first-place vote at #13 and four keeps at #14 and was beaten both times by
 * the same two objections: the door schedule and the hardware sets are owned
 * and NUMBERED upstream by the architect and the hardware consultant, and
 * rated-assembly data sits in the middle of the trade. The #14 entry closed by
 * saying what it needed next was NOT another hearing — it was a kit concept
 * that survives its own kill. That is what this file is.
 *
 * THE KILL WAS AIMED AT THE WRONG COMPANY, and the rack had already written
 * the distinction down without noticing: masonry/items.js names "Hollow metal
 * / door supplier", framing/items.js names "Doors & hardware", and
 * low-voltage/items.js names "Door hardware" — three different parties, and
 * only ONE of them owns a schedule. For the DISTRIBUTOR that schedule and
 * those sets are the product, and a hub for him would be dead on arrival. For
 * the INSTALLER the schedule is an INPUT HE RECEIVES, and everything he sends
 * back is field information the schedule does not contain and cannot.
 *
 * THE TEST THAT MAKES THAT CHECKABLE, rather than a matter of taste, and the
 * rule every page in this kit is built against: WE VIOLATE THE SYSTEM OF
 * RECORD WHEN OUR PAGE BECOMES A SECOND PLACE THE RECORD LIVES. Three
 * crossings, any one of which is fatal: (a) we reproduce the owner's CONTENT —
 * the set's contents, the schedule's columns; (b) we issue our own IDENTIFIER
 * for the same thing; (c) we are built to be filed INSTEAD of the owner's
 * form. Citing "Opening 101A" does none of those. It is an ADDRESS, not the
 * record. "101A: wall measured 6-1/4, jamb depth measured 4-7/8, it swings the
 * other way" adds what the schedule does not hold and cannot be mistaken for
 * it. ADDRESS IS CLEAN. CONTENT IS DEAD. A RIVAL NUMBER IS DEAD.
 *
 * FIVE SHIPPED KITS NAME THIS RECEIVER AND NONE OF THEM COULD ADDRESS HIM —
 * flooring, framing, low-voltage, masonry and painting — tied for the most on
 * the rack, and the two it was tied with are both dead on the safety rail:
 * fire sprinkler (hydraulic calcs sealed by a NICET III or a PE, the material
 * and test certificate printed inside the standard, ITM reports owned and
 * numbered by third-party portals) and structural steel (the chapter 17
 * special-inspection record, and a ban list that names torque specs outright).
 * Doors is the top BUILDABLE nominee left, which is a different and better
 * claim than being the most mentioned.
 *
 * THE LIVE GAP IT CLOSES, and the reason it is worth more than its headcount:
 * low-voltage/items.js already ships `doorprep` with `who: "doors"` — "electric
 * hinge on that leaf · raceway in the door for the loop · frame prepped for the
 * strike · header prepped for the mag · mullion prepped for the reader" — an
 * ask aimed at a man who, until this directory existed, had nowhere to answer
 * it. Access control depends on somebody prepping a leaf, and the kit that
 * sells access control could not reach him.
 *
 * THE HONEST DEMERIT, WRITTEN DOWN AT STAND-UP SO NO LATER CYCLE HAS TO
 * REDISCOVER IT: this trade survives BY DISCIPLINE, NOT STRUCTURALLY.
 * Flooring survives structurally — its numbers are warranty terms that
 * disagree with each other, so there is no number to supply even if we wanted
 * to. Doors is not like that. Rated-assembly data sits in the middle of the
 * trade and sooner or later somebody proposes a label field. The counter-
 * evidence is on this same rack: low-voltage ships a fire-alarm kit under an
 * identically hard refusal list and did not go hollow. Discipline-survival is
 * proven possible here. It is simply more expensive to hold, and the price is
 * the list below.
 *
 * AND THE RISK THAT IS NOT ABOUT DOCUMENTS AT ALL, named by two independent
 * lenses and NOT solved by this file: this trade may not have a NAME its
 * people call themselves. A sparky calls himself a sparky; the man hanging
 * leaves in a union market calls himself a carpenter out of a local. If
 * nothing here pulls on its own, doors is a set of pages rather than a hub,
 * and the pages belong stapled into framing and gc. That is a measurement to
 * take, not an argument to have — and it is why this hub is named for the
 * SCOPE ("Doors & Hardware", the way the schedule and the bid package say it)
 * rather than for a job title nobody agrees on.
 *
 * WHAT THIS TRADE IS NOT ALLOWED TO SHIP, decided before a line was written
 * and not negotiable by a later cycle:
 *   - NO FIRE LABEL VALUE, EVER. Not a rating, not what a label permits, not
 *     whether a label is intact, not a label-to-assembly crosswalk. He may
 *     QUOTE what a tag in front of him says — "frame tag reads 90, leaf tag
 *     reads 45 at 214, somebody needs to make a call" — and that is a report
 *     of a discrepancy travelling to the person who resolves it. It is never
 *     this kit saying what either number is worth.
 *   - NO CLEARANCE, GAP OR UNDERCUT DIMENSION as a value, default or
 *     "typical". What he measured with his own tape rides; what a gap is
 *     allowed to be belongs to the standard and the inspector.
 *   - NO CLOSER SETTING of any kind: no spring size, no sweep, latch or
 *     backcheck adjustment, no opening-force figure, no delayed-action time.
 *   - NO HARDWARE SET CONTENTS and no set number carrying contents. A set
 *     number may ride as an ADDRESS, exactly as an opening number does. The
 *     moment the contents ride with it we have rebuilt the consultant's
 *     document, and that is crossing (a).
 *   - NO DOOR SCHEDULE. Not a copy, not a subset, not "just the columns I
 *     need". The schedule is the architect's, it is numbered, and a second
 *     copy on a phone is the double entry this whole program exists to refuse.
 *   - NO KEYING OR BITTING PAGE: no keyed-alike groups, no master or
 *     grand-master structure, no bitting, no cylinder crosswalk. The keying
 *     ASK — decide by this date or these go in construction cores — is a note
 *     he sends. The keying SCHEDULE is somebody else's document and stays it.
 *   - NO ACCESSIBILITY NUMBER: no opening force, no maneuvering clearance, no
 *     threshold height, no hardware mounting height, no closing speed.
 *   - NO ANCHOR, FASTENER OR GROUT SCHEDULE, no anchor spacing, no plumb or
 *     twist tolerance, no rough-opening dimension supplied by us. What a tick
 *     asks for is what he read off his own approved shop drawings.
 *   - NO ELECTRIFIED-OPENING SPEC: no voltage, no wire size, no device model,
 *     no fail-safe/fail-secure determination, no interface to an alarm. He can
 *     say an opening HAS a release or a reader because his own hardware
 *     submittal says so; what it must DO on alarm belongs to the fire alarm
 *     submittal, the engineer's riser and the AHJ.
 *   - NO ANNUAL FIRE DOOR INSPECTION FORM, and this is the single most
 *     dangerous page anybody will ever propose for this hub. It is a certified
 *     inspection with a certified inspector behind it. We do not build it, we
 *     do not build something shaped like it, and we do not build a checklist a
 *     super could mistake for it.
 *   - NO RELEASE VERDICT: no page here says an opening is complete, compliant,
 *     acceptable, or that a leaf swings free. What he did, where, and what is
 *     left — in his words, dated — is the entire document.
 * Every refusal above is a place where the honest tool is a picker that
 * structures what the USER states off his own tape, his own submittal and his
 * own shop drawing. We ship that instead, every time.
 *
 * Note what is NOT here: a copy of the runtime. shared/toolkit.js is
 * trade-agnostic and this file is the whole of what makes it the doors kit.
 *
 * Load order on every page:
 *   <script src="trade.js"></script>
 *   <script src="tools.js"></script>
 *   <script src="../shared/toolkit.js"></script>
 *
 * Author: Aldrin Payopay <aldrin.gdf@gmail.com>
 */
