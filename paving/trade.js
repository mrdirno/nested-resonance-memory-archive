/* PAVING & STRIPING FIELD TOOLKIT — the trade config.
 *
 * TRADE #17, AND THE FIRST ONE THE RACK HAD ALREADY WRITTEN A LETTER TO. Four
 * independent lenses — a field hand, a population count, the doctrine lens that
 * reads the record, and the boundary lens that reads every shipped items.js —
 * scored nine candidates and this one came out 70 · 70 · 62 · 78: first on
 * population and boundary, second on the other two, vetoed by none. Exteriors
 * (siding and gutters) took the field hand at 74 and fell off on doctrine and
 * boundary (58 · 52); final-clean took doctrine at 70 and had no crew to speak
 * of (47 · 36). Not unanimous the way landscape was, and the two dissents are
 * not a footnote — they are the design constraints this directory is built
 * under:
 *
 *   THE DOCTRINE LENS (62, not first) said it in one sentence: "the kill-in-
 *   waiting is the ADA stall count near the centre of his layout page." So the
 *   layout page — the pinned one — structures WHAT THE SHEET SAYS, as an
 *   address (sheet, rev, what it draws there, quoted), and WHAT HIS TAPE FOUND,
 *   and never once carries a count table, a stall dimension, an aisle width, a
 *   slope limit or an accessible-stall count of its own. The page asks WHICH
 *   ONE GOES and stops.
 *
 *   THE FIELD HAND (70, second to exteriors) said the crew is real and thumb-
 *   types lists — but the paving half has an office more often than the
 *   striping half does. So the kit speaks to the FOREMAN and to the owner-
 *   operator, and never to the estimator. Nothing here prices, tallies or
 *   totals.
 *
 * WHY THE BOUNDARY LENS PUT IT FIRST (78), and why that is the finding: this is
 * the only candidate on the rack with a receiver chip AND a letter already
 * written to it. landscape/items.js carries `{ v: "paving", label: "Paving /
 * striping" }` and then actually writes him one — "Walk my sleeves before the
 * base rolls", with the spec lines "Finish elevation at the curb and the walk,
 * so my grade meets yours without a lip" and "Once it's paved it's a saw cut —
 * and an argument". sitework/items.js carries a SECOND chip, "Paving / base",
 * an orphan whose nine asks never route to him. low-voltage says "Pipe out to
 * the gate before paving" and aims it at the electrician; electrical says "Saw
 * cut and patch the asphalt"; gc lumps him in as "Site concrete, paving,
 * striping, landscape". And "Before you pave" (landscape/items.js) is the one
 * irreversible gate word on the site rack that a shipped kit counts DOWN to and
 * no hub owns. Two mailboxes, one letter, and nobody at the address. Three of
 * the four lenses independently named the LAYOUT-DISCREPANCY page as the one
 * page no other hub could write; the boundary lens named the receiver-side
 * crossing log. Both ship. The layout page is pinned.
 *
 * WHO HE IS. The foreman on an asphalt paving crew on commercial lots, drives
 * and subdivisions — a paver, a roller or two, rakes and lutes, and a haul
 * route of trucks coming off a plant ticket — and the owner-operator of a
 * sealcoat & striping outfit: one or two trucks, a striper, a blower, stencils,
 * cones and tape, laying a plan out on a finished surface and closing half a
 * lot for a night. Two hats, often two companies; the rack has them as one
 * chip. He is on the job LAST — after the curb, the sleeves, the lids, the pole
 * bases and every other trade's trench — and on an occupied lot he is the man
 * whose cones decide where two hundred people park tonight.
 *
 * WHAT THIS HUB IS NOT, decided before a line was written: it is not HIGHWAY
 * or DOT paving. That half is bonded, inspected and numbered by the agency —
 * daily diaries, density lots, agency forms — and every certified-data problem
 * this trade has lives there. And it is not the MAINTENANCE ROUTE on the
 * striper's side: the customer list at street addresses, the route sheet, the
 * recurring account — scoped out the way landscape scoped out the spray log
 * and doors scoped out the distributor. The first wish that asks for a route
 * sheet is a wish for the page this hub will never build.
 *
 * THE NAME COLLISION, and it is a rule for every word in this directory: on
 * this rack "PAVER" means a masonry/hardscape paver — the BRICK. landscape/
 * items.js says "Pavers on base" and means the thing masonry lays. The machine
 * this crew runs is "the paver" only inside a sentence that makes it a machine.
 * The brand word here is PAVING, the surface is THE MAT, the plan side is THE
 * LAYOUT, and the man is "the paving crew" or "the striper". "Pavers" is never
 * a name for this trade's work — not a page, not a chip, not a heading — or
 * the rack has two trades wearing one word.
 *
 * THE HONEST DEMERITS, written at stand-up so no later cycle rediscovers them:
 *   (1) two trades in one hat — the paving crew and the striping outfit are
 *       often two companies, and the kit serves the foreman of either, not the
 *       estimator of the first;
 *   (2) the word "paver" — masonry's brick, never ours, see above;
 *   (3) not a unanimous panel: doctrine and the field hand both ranked another
 *       trade first, and their reasons are the constraints written above;
 *   (4) one genuinely engineered pressure point on each hat — the mix and the
 *       density on the paving side, the accessible stalls and the fire lane on
 *       the striping side — and the first wish on each will be "can it work out
 *       my stall count" / "what temp should I be laying at": permanently no;
 *   (5) his gate ladder is BORROWED at the top — "before the base rolls" is
 *       sitework's day — and OWNED at the bottom: after the mat there is no
 *       taking it back, only a saw cut, a grind-out and an argument about whose
 *       day that costs. That is why the pinned page is the layout walk and not
 *       the pour.
 *
 * THE HARD REFUSAL — what this trade is not allowed to ship, and not negotiable
 * by a later cycle:
 *   1.  NO MIX DESIGN, mix temperature, lay-down or compaction temperature,
 *       density, compaction percentage, thickness, lift or tonnage-per-area
 *       (yield) math — not as a value, a default, a placeholder or a "typical".
 *       The lab and the plant own those; a ticket number rides as an address.
 *   2.  NO ADA / accessible-stall COUNT, stall or aisle DIMENSION, slope limit,
 *       sign height or symbol spec; NO stall-count table of any kind. The page
 *       says what the SHEET draws (sheet, rev, quoted) and what HIS TAPE found,
 *       and asks the civil or the owner which one goes.
 *   3.  NO FIRE-LANE determination, length, width or marking spec — that is the
 *       fire marshal's. NO MUTCD or traffic-sign spec.
 *   4.  NO TRAFFIC-CONTROL PLAN, flagger plan, lane-closure plan or detour: an
 *       engineered, permitted document. We ask WHO holds it and stop.
 *   5.  NO CURE TIME, open-to-traffic time, sealcoat product, application rate,
 *       paint spec, dry time or "how long to keep cars off". The manufacturer's
 *       sheet and his own spec sheet own that; the page carries what HE states,
 *       in his words, copied off his sheet.
 *   6.  NO SCALE OR PLANT TICKET of ours, no load count turned into a yield or
 *       a "short load" verdict, no invoice, no unit price.
 *   7.  NO VERDICT that a subgrade, a base or a lift passed, failed or is "to
 *       spec": the lab's numbered report, the civil's call.
 *   8.  NO PROOF-ROLL VERDICT of ours. "I watched it, here is what I saw where
 *       the truck sat" is the whole of what a row may say.
 *   9.  NO TOW AUTHORIZATION, no license-plate list, no tenant roster, no
 *       customer address list. Privacy, and not ours to hold.
 *   10. NO WEATHER THRESHOLD — no air or surface temperature minimum. "I'm not
 *       paving today, here's what I saw" in his own words is the record.
 *   11. NO DRAINAGE OR GRADE ENGINEERING. A birdbath is a place he saw water
 *       sit, named; no slope number of ours, ever.
 *   12. NO RELEASE VERDICT, EVER: nothing on any page says the lot is open,
 *       accepted, complete or warrantable.
 * Every refusal above is a place where the honest tool is a picker that
 * structures what the USER states off his own sheet, his own tape, his own
 * ticket and his own contract. We ship that instead, every time.
 *
 * Note what is NOT here: a copy of the runtime. shared/toolkit.js is
 * trade-agnostic and this file is the whole of what makes it the paving kit.
 *
 * Load order on every page:
 *   <script src="trade.js"></script>
 *   <script src="tools.js"></script>
 *   <script src="../shared/toolkit.js"></script>
 *
 * Author: Aldrin Payopay <aldrin.gdf@gmail.com>
 */
